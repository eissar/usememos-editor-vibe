const out = await Bun.build({
  entrypoints: [new URL("./main.ts", import.meta.url).pathname],
  target: "browser",
  format: "iife",
  minify: true,
});

if (!out.success) {
  console.error("ui build failed");
  for (const log of out.logs) console.error(String(log));
  process.exit(1);
}

const js = await out.outputs[0]!.text();
const html = await Bun.file(new URL("./index.html", import.meta.url).pathname).text();

const tag = '<script type="module" src="./main.ts"></script>';
if (!html.includes(tag)) {
  console.error("index.html is missing the main.ts script tag");
  process.exit(1);
}

// The page ships as two strings. UI_HTML (markup and styles) goes through
// webview_set_html, which on Windows is WebView2's NavigateToString: that
// refuses documents over 2 MB (as UTF-16) and the failure is silent, leaving a
// blank window. UI_JS (the bundle, well over that once code languages are in)
// goes through webview_init, which has no such limit, and starts the app once
// the document has parsed. The marker attribute keeps it from running in any
// other document the webview loads.
const MARKER = 'data-app="text-edit"';
const shell = html.replace(tag, () => "").replace("<html", () => `<html ${MARKER}`);
if (!shell.includes(MARKER)) {
  console.error("index.html has no <html> tag to mark");
  process.exit(1);
}
const boot =
  `(function(){function start(){if(document.documentElement.getAttribute("data-app")!=="text-edit")return;` +
  `try{${js}\n}catch(e){var p=document.createElement("pre");p.style.cssText="margin:0;padding:16px;color:#e06c75;background:#16181d;white-space:pre-wrap";` +
  `p.textContent="text-edit: the editor script failed to start:\\n"+(e&&e.stack||e);document.body.replaceChildren(p);}}if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",start);else start();})();`;

const dest = new URL("../native/ui_html.h", import.meta.url).pathname;
await Bun.write(
  dest,
  `/* generated by ui/build.ts - do not edit */\n` +
    `static const char *UI_HTML =\n${cLiteral(shell)};\n` +
    `static const char *UI_JS =\n${cLiteral(boot)};\n`,
);

const kib = (t: string) => (Buffer.byteLength(t) / 1024).toFixed(0);
console.log(`ui: html ${kib(shell)} KiB, js ${kib(boot)} KiB -> native/ui_html.h`);

function cLiteral(s: string): string {
  // Escape everything outside printable ASCII. Emitting UTF-8 bytes raw makes
  // the literal depend on the compiler's source charset, and the webview then
  // decodes them as Latin-1. Octal escapes are at most three digits, so they cannot swallow a
  // following character the way \x can.
  const bytes = new TextEncoder().encode(s);
  const parts: string[] = [];
  let chunk = "";

  for (const b of bytes) {
    let piece: string;
    if (b === 0x5c) piece = "\\\\";
    else if (b === 0x22) piece = '\\"';
    else if (b === 0x0a) piece = "\\n";
    // "??(" and friends are C trigraphs; minified JS contains "??(" from `??`.
    else if (b === 0x3f) piece = "\\?";
    else if (b >= 0x20 && b <= 0x7e) piece = String.fromCharCode(b);
    else piece = "\\" + b.toString(8).padStart(3, "0");

    chunk += piece;
    if (chunk.length >= 4000) {
      parts.push(`  "${chunk}"`);
      chunk = "";
    }
  }
  if (chunk.length > 0) parts.push(`  "${chunk}"`);
  return parts.join("\n");
}
