const out = await Bun.build({
  entrypoints: [new URL("./main.ts", import.meta.url).pathname],
  target: "browser",
  format: "iife",
  minify: true,
});

if (!out.success) {
  console.error("ui build failed");
  for (const log of out.logs) console.error(String(log));
  process.exit(1);
}

const js = await out.outputs[0]!.text();
const html = await Bun.file(new URL("./index.html", import.meta.url).pathname).text();

const tag = '<script type="module" src="./main.ts"></script>';
if (!html.includes(tag)) {
  console.error("index.html is missing the main.ts script tag");
  process.exit(1);
}

// Inline the bundle so the page is a single string with no fetches: the host
// calls webview_set_html and there is no server to serve anything.
// Function replacer, not a string: `$&`, `$\`` and `$'` inside the bundle would
// otherwise be expanded as replacement patterns and splice the matched tag into
// the script. Minified CodeMirror contains `$&`, and that is exactly how the
// page ended up with nested <script> tags and rendered as text.
const page = html.replace(tag, () => `<script>${js}</script>`);

const dest = new URL("../native/ui_html.h", import.meta.url).pathname;
await Bun.write(dest, `/* generated by ui/build.ts - do not edit */\nstatic const char *UI_HTML =\n${cLiteral(page)};\n`);

console.log(`ui: ${(Buffer.byteLength(page) / 1024).toFixed(0)} KiB -> native/ui_html.h`);

function cLiteral(s: string): string {
  // Escape everything outside printable ASCII. Emitting UTF-8 bytes raw makes
  // the literal depend on the compiler's source charset, and the webview then
  // decodes them as Latin-1: "⌘" arrives as "â\x8c\x98" and the page renders as
  // text. Octal escapes are at most three digits, so they cannot swallow a
  // following character the way \x can.
  const bytes = new TextEncoder().encode(s);
  const parts: string[] = [];
  let chunk = "";

  for (const b of bytes) {
    let piece: string;
    if (b === 0x5c) piece = "\\\\";
    else if (b === 0x22) piece = '\\"';
    else if (b === 0x0a) piece = "\\n";
    else if (b >= 0x20 && b <= 0x7e) piece = String.fromCharCode(b);
    else piece = "\\" + b.toString(8).padStart(3, "0");

    chunk += piece;
    if (chunk.length >= 4000) {
      parts.push(`  "${chunk}"`);
      chunk = "";
    }
  }
  if (chunk.length > 0) parts.push(`  "${chunk}"`);
  return parts.join("\n");
}
